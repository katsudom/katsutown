const CELL = 9;
const COLS = 16;
const FONT_W = 160;
const FONT_H = 64;

export function buildFont() {
  const c = new Canvas(FONT_W, FONT_H);
  const table = new Map(
    GLYPHS.map(([ch, y0, spec]) => [ch.charCodeAt(0), { y0, rows: spec.split('/') }]),
  );
  const chars = [];
  const ids = [...Array.from({ length: 95 }, (_, i) => 32 + i), 183, 8211, 8594, 8217];
  for (const [idx, id] of ids.entries()) {
    const cx = 1 + (idx % COLS) * CELL;
    const cy = 1 + Math.floor(idx / COLS) * CELL;
    if (id === 32) {
      chars.push({ id, x: cx, y: cy, width: 0, height: 0, xadvance: 4 });
      continue;
    }
    const g = table.get(id);
    if (!g) throw new Error(`font: missing glyph for ASCII ${id}`);
    const width = Math.max(...g.rows.map((r) => r.length));
    g.rows.forEach((row, j) => {
      for (let i = 0; i < row.length; i++) {
        if (row[i] === '#') c.set(cx + i, cy + g.y0 + j, 'white');
      }
    });
    chars.push({ id, x: cx, y: cy, width, height: 8, xadvance: width + 1 });
  }
  const lines = chars.map(
    (g) =>
      `    <char id="${g.id}" x="${g.x}" y="${g.y}" width="${g.width}" height="${g.height}" xoffset="0" yoffset="0" xadvance="${g.xadvance}" page="0" chnl="15"/>`,
  );
  const xml = `<?xml version="1.0"?>
<font>
  <info face="KatsudomPixel" size="8" bold="0" italic="0" charset="" unicode="1" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="1,1"/>
  <common lineHeight="10" base="6" scaleW="${FONT_W}" scaleH="${FONT_H}" pages="1" packed="0"/>
  <pages>
    <page id="0" file="font-pixel.png"/>
  </pages>
  <chars count="${chars.length}">
${lines.join('\n')}
  </chars>
</font>
`;
  return {
    canvas: c,
    xml,
    pngPath: 'assets/ui/font-pixel.png',
    xmlPath: 'assets/ui/font-pixel.xml',
  };
}
